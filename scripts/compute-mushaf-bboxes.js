#!/usr/bin/env node
/*
 * Computes a tight content bounding box for every mushaf-page SVG so we can
 * rewrite the viewBox at load-time and have each page render centered. The
 * source SVGs were authored for two-page spreads — odd pages have content
 * drifted toward the (left) spine, even pages toward the (right) spine — so
 * a one-size-fits-all viewBox leaves them visibly off-center.
 *
 * Output: src/db/mushafSvgBBoxes.ts — a const map of pageNumber -> [x, y, w, h].
 */

const fs = require('fs');
const path = require('path');

const ASSETS_DIR = path.resolve(__dirname, '..', 'assets', 'mushaf-svg');
const OUTPUT_PATH = path.resolve(__dirname, '..', 'src', 'db', 'mushafSvgBBoxes.ts');

// Each mushaf-page SVG embeds a `data-rect="minX,minY,maxX,maxY"` attribute on
// the `md-page-inner` group giving the exact body-text bbox in viewBox units.
// We use that directly — much more accurate than reconstructing the bbox from
// path-data anchor points (which under-counted curve extent and pulled in
// off-body decoration like juz-name + surah-name + page-number, dragging the
// computed center away from where the user actually reads).
function computeBBox(xml) {
  const m = xml.match(/<g\s+id="md-page-inner"[^>]*data-rect="([^"]+)"/);
  if (!m) return null;
  const parts = m[1].split(',').map((s) => parseFloat(s.trim()));
  if (parts.length !== 4 || parts.some((n) => Number.isNaN(n))) return null;
  const [minX, minY, maxX, maxY] = parts;
  return { minX, minY, maxX, maxY };
}

const files = fs
  .readdirSync(ASSETS_DIR)
  .filter((f) => /^\d{3}\.qsvg$/.test(f))
  .sort();

const bboxes = {};
const missing = [];
for (const f of files) {
  const page = parseInt(f.slice(0, 3), 10);
  const xml = fs.readFileSync(path.join(ASSETS_DIR, f), 'utf8');
  const rect = computeBBox(xml);
  if (!rect) {
    missing.push(page);
    continue;
  }
  const { minX, minY, maxX, maxY } = rect;
  bboxes[page] = {
    minX, minY, maxX, maxY,
    w: maxX - minX,
    h: maxY - minY,
    cx: (minX + maxX) / 2,
    cy: (minY + maxY) / 2,
  };
  if (page % 100 === 0) console.error(`processed page ${page}`);
}
if (missing.length) console.error(`no data-rect on ${missing.length} pages: ${missing.join(', ')}`);

const widths = Object.values(bboxes).map((b) => b.w);
const heights = Object.values(bboxes).map((b) => b.h);
const maxW = Math.max(...widths);
const maxH = Math.max(...heights);
const avgW = widths.reduce((a, b) => a + b, 0) / widths.length;
const avgH = heights.reduce((a, b) => a + b, 0) / heights.length;
console.error(`bbox widths:  min=${Math.min(...widths).toFixed(2)} avg=${avgW.toFixed(2)} max=${maxW.toFixed(2)}`);
console.error(`bbox heights: min=${Math.min(...heights).toFixed(2)} avg=${avgH.toFixed(2)} max=${maxH.toFixed(2)}`);

const lines = [
  '// AUTO-GENERATED by scripts/compute-mushaf-bboxes.js — do not edit.',
  '// Tight content bbox per page so we can rewrite the SVG viewBox at load',
  '// time and have each page center on its own content. Source SVGs were',
  '// authored for two-page spreads, so odd/even pages have content drifted',
  '// toward their respective spine — without this, pages render off-center.',
  '',
  '// [centerX, centerY] of the page\'s content bbox, in source viewBox units',
  '// (0..382.68 horizontal, 0..547.09 vertical).',
  'export const MUSHAF_PAGE_CONTENT_CENTER: Record<number, [number, number]> = {',
];

for (const f of files) {
  const page = parseInt(f.slice(0, 3), 10);
  const b = bboxes[page];
  lines.push(`  ${page}: [${b.cx.toFixed(2)}, ${b.cy.toFixed(2)}],`);
}

lines.push('};');
lines.push('');

fs.writeFileSync(OUTPUT_PATH, lines.join('\n'));
console.error(`wrote ${OUTPUT_PATH} (${files.length} pages)`);
